def clean_arabic_post_ocr(text: str) -> str:
    """Applies orthographic unification, clause-number stripping, and lexicon fixes."""
    if not text:
        return ""

    # 1. Strip Urdu/Persian full stop (۔) and normalize basic Arabic orthography
    text = text.replace("۔", "")
    text = normalize_arabic(text)
    text = text.replace("ى", "ي")

    # 2. Strip orphan clause numbers (١, ٢, ٣, ٤) at the start of the article or after periods
    text = re.sub(
        r"(?:^|(?<=[\.\:؛]))\s*[\(\[]?[١٢٣٤1234][\)\]\-\.]?\s*(?=[أ-ي])", " ", text
    )

    # 3. Fix mid-sentence stray periods
    for wrong_period, fixed_phrase in MID_SENTENCE_PERIOD_FIXES:
        text = text.replace(wrong_period, fixed_phrase)

    # 4. Apply word-level and phrase-level OCR typo dictionary
    for wrong, right in OCR_TYPO_FIXES.items():
        text = text.replace(wrong, right)

    # 5. Restore colons on introductory list headers
    text = re.sub(
        r"(الاحوال الاتية|الشروط الاتية|الحالات الاتية|الحالتين الاتيتين|الحقوق الاتية|الاحكام الاتية|ما ياتي|ما يلي|كالاتي)\s*[\.]?",
        r"\1:",
        text,
    )

    # 6. Normalize whitespace and punctuation spacing
    text = re.sub(r"\s+", " ", text).strip()
    text = re.sub(r"\s+([.،؛:؟!])", r"\1", text)
    text = re.sub(r"([،؛:])(?=[أ-ي])", r"\1 ", text)

    if text and not text.endswith((".", "!", "؟")):
        text += "."

    return text


def postprocess_corpus(
    raw_path: Path = settings.RAW_CORPUS_PATH,
    output_path: Path = settings.PROCESSED_CORPUS_PATH,
) -> list[ArticleSchema]:
    """Loads raw_corpus.json, applies typo fixes and overrides, validates, and writes corpus.json."""
    raw_records: list[dict[str, Any]] = json.loads(raw_path.read_text(encoding="utf-8"))
    validated_articles: list[ArticleSchema] = []
    override_count = 0

    for rec in raw_records:
        art_num = rec["article_number"]
        if not rec["is_repealed"]:
            if art_num in ARTICLE_AR_OVERRIDES:
                rec["ar_text"] = clean_arabic_post_ocr(ARTICLE_AR_OVERRIDES[art_num])
                override_count += 1
            else:
                rec["ar_text"] = clean_arabic_post_ocr(rec.get("ar_text") or "")

            rec["en_text"] = normalize_english(rec.get("en_text") or "")

        validated_articles.append(ArticleSchema(**rec))

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        json.dumps(
            [a.model_dump() for a in validated_articles], ensure_ascii=False, indent=2
        ),
        encoding="utf-8",
    )
    logger.info(
        f"Post-processed {len(validated_articles)} articles "
        f"({override_count} manual overrides applied) -> {output_path}"
    )
    return validated_articles


